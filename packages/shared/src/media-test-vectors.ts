function page(packet: Uint8Array, sequence: number, flags: number): Uint8Array {
  const lacing: number[] = [];
  let left = packet.length;
  while (left >= 255) {
    lacing.push(255);
    left -= 255;
  }
  lacing.push(left);
  const result = join(
    textBytes('OggS'),
    new Uint8Array([0, flags]),
    new Uint8Array(8),
    uint32(42, true),
    uint32(sequence, true),
    new Uint8Array(4),
    new Uint8Array([lacing.length]),
    new Uint8Array(lacing),
    packet,
  );
  let crc = 0;
  for (const value of result) {
    crc ^= value << 24;
    for (let bit = 0; bit < 8; bit++)
      crc = ((crc << 1) ^ (crc & 0x80000000 ? 0x04c11db7 : 0)) >>> 0;
  }
  new DataView(result.buffer).setUint32(22, crc, true);
  return result;
}
export function opus(commentBytes = 0): Uint8Array {
  return join(
    page(join(textBytes('OpusHead'), hex('0101380180bb0000000000')), 0, 2),
    page(
      join(
        textBytes('OpusTags'),
        uint32(commentBytes, true),
        new Uint8Array(commentBytes),
        uint32(0, true),
      ),
      1,
      0,
    ),
    page(hex('f8fffe'), 2, 4),
  );
}
