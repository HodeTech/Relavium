/** Internal test data only, independently specified from public format layouts; never exported by barrel. */
export function hex(value: string): Uint8Array {
  const result = new Uint8Array(value.length / 2);
  for (let i = 0; i < result.length; i++)
    result[i] = Number.parseInt(value.slice(i * 2, i * 2 + 2), 16);
  return result;
}
export function join(...items: readonly Uint8Array[]): Uint8Array {
  let n = 0;
  for (const item of items) n += item.length;
  const result = new Uint8Array(n);
  let at = 0;
  for (const item of items) {
    result.set(item, at);
    at += item.length;
  }
  return result;
}
export function textBytes(value: string): Uint8Array {
  return Uint8Array.from([...value].map((c) => c.charCodeAt(0)));
}
export function uint32(value: number, little = false): Uint8Array {
  const b = new Uint8Array(4);
  new DataView(b.buffer).setUint32(0, value, little);
  return b;
}
