export function box(name: string, ...payload: readonly Uint8Array[]): Uint8Array {
  const body = join(...payload);
  return join(uint32(8 + body.length), textBytes(name), body);
}
export function mp4Video(
  padding = 1,
  codec: 'avc1' | 'hvc1' | 'vp09' | 'av01' = 'avc1',
): Uint8Array {
  const visual = new Uint8Array(78),
    v = new DataView(visual.buffer);
  v.setUint16(6, 1);
  v.setUint16(24, 1);
  v.setUint16(26, 1);
  v.setUint16(40, 1);
  v.setUint16(74, 24);
  v.setUint16(76, 65535);
  const configs = {
    avc1: ['avcC', hex('0142001effe100016701000168')],
    hvc1: [
      'hvcC',
      hex('0101000000000000000000001ef000fcfdf8f800000f022100010002420122000100024401'),
    ],
    vp09: ['vpcC', hex('01000000000a800101010000')],
    av01: ['av1C', hex('81000c00')],
  } satisfies Record<string, [string, Uint8Array]>;
  const [kind, config] = configs[codec];
  const stsd = box('stsd', new Uint8Array(4), uint32(1), box(codec, visual, box(kind, config)));
  const hdlr = box('hdlr', new Uint8Array(8), textBytes('vide'), new Uint8Array(12));
  const tkhd = new Uint8Array(84),
    mdhd = new Uint8Array(24);
  new DataView(tkhd.buffer).setUint32(12, 1);
  new DataView(mdhd.buffer).setUint32(12, 1000);
  const track = box(
    'trak',
    box('tkhd', tkhd),
    box('mdia', box('mdhd', mdhd), hdlr, box('minf', box('stbl', stsd))),
  );
  return join(
    box('ftyp', textBytes('isom'), new Uint8Array(4), textBytes('isom')),
    box('mdat', new Uint8Array(padding)),
    box('moov', track),
  );
}
export function ebml(id: string, payload: Uint8Array): Uint8Array {
  const n = payload.length;
  let size: Uint8Array;
  if (n < 127) size = new Uint8Array([128 + n]);
  else if (n < 16383) size = new Uint8Array([64 + (n >> 8), n & 255]);
  else size = new Uint8Array([32 + (n >> 16), (n >> 8) & 255, n & 255]);
  return join(hex(id), size, payload);
}
export function webmVideo(
  padding = 1,
  options: {
    readonly codec?: 'V_VP8' | 'V_VP9' | 'V_AV1';
    readonly contentEncodings?: Uint8Array;
  } = {},
): Uint8Array {
  const header = ebml('1a45dfa3', ebml('4282', textBytes('webm')));
  const track = ebml(
    'ae',
    join(
      ebml('d7', hex('01')),
      ebml('83', hex('01')),
      ebml('86', textBytes(options.codec ?? 'V_VP8')),
      ebml('e0', join(ebml('b0', hex('01')), ebml('ba', hex('01')))),
      ...(options.contentEncodings === undefined ? [] : [ebml('6d80', options.contentEncodings)]),
    ),
  );
  const cluster = ebml('1f43b675', ebml('a3', join(hex('81000080'), new Uint8Array(padding))));
  return join(header, ebml('18538067', join(cluster, ebml('1654ae6b', track))));
}
export function pdfDocument(padding = 0): Uint8Array {
  const body = '%PDF-1.7\n1 0 obj\n<< /Type /Catalog >>\nendobj\n' + ' '.repeat(padding),
    offset = body.length;
  return textBytes(
    body +
      `xref\n0 2\n0000000000 65535 f \n0000000009 00000 n \ntrailer\n<< /Size 2 /Root 1 0 R >>\nstartxref\n${offset}\n%%EOF\n`,
  );
}
