export function wave(samples = 2): Uint8Array {
  const fmt = hex('01000100401f0000803e000002001000');
  const data = new Uint8Array(samples);
  return join(
    textBytes('RIFF'),
    uint32(36 + samples + (samples % 2), true),
    textBytes('WAVEfmt '),
    uint32(16, true),
    fmt,
    textBytes('data'),
    uint32(samples, true),
    data,
    ...(samples % 2 ? [new Uint8Array(1)] : []),
  );
}
